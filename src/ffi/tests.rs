fn cdef(cts: &mut CTState, s: &str) -> Result<(), FfiError> {
    cparse(
        cts,
        s.as_bytes(),
        CPARSE_MODE_MULTI | CPARSE_MODE_DIRECT,
        Some(&[]),
    )
    .map(|_| ())
}

fn typeof_(cts: &mut CTState, s: &str) -> Result<CTypeID, FfiError> {
    cparse(
        cts,
        s.as_bytes(),
        CPARSE_MODE_ABSTRACT | CPARSE_MODE_NOIMPLICIT,
        Some(&[]),
    )
}

fn msg(e: FfiError) -> String {
    String::from_utf8(e.message().to_vec()).unwrap()
}

/// `ffi.sizeof(ct [, nelem])`.
fn sizeof_(cts: &CTState, id: CTypeID, nelem: Option<u32>) -> Option<u32> {
    let ct = cts.rawref(id);
    let info = cts.get(ct).info;
    let sz = if ctype_isvltype(info) {
        cts.vlsize(ct, nelem.expect("VLA size"))
    } else if ctype_hassize(info) {
        cts.get(ct).size
    } else {
        CTSIZE_INVALID
    };
    (sz != CTSIZE_INVALID).then_some(sz)
}

/// `ffi.alignof(ct)`.
fn alignof_(cts: &CTState, id: CTypeID) -> u32 {
    1 << ctype_align(cts.info_raw(id).0)
}

/// `tostring(ctype)`.
fn tostring(cts: &CTState, id: CTypeID) -> String {
    format!("ctype<{}>", String::from_utf8(cts.repr(id, None)).unwrap())
}

/// `ffi.offsetof(ct, field)`: offset, bit position, bit size.
fn offsetof_(cts: &CTState, id: CTypeID, name: &str) -> (i64, i64, i64) {
    let ct = cts.rawref(id);
    let c = cts.get(ct);
    if ctype_isstruct(c.info)
        && c.size != CTSIZE_INVALID
        && let Some((f, ofs)) = cts.getfield(ct, name.as_bytes())
    {
        let fi = cts.get(f).info;
        if ctype_isfield(fi) {
            return (ofs as i64, -1, -1);
        } else if ctype_isbitfield(fi) {
            return (ofs as i64, ctype_bitpos(fi) as i64, ctype_bitbsz(fi) as i64);
        }
    }
    (-1, -1, -1)
}

