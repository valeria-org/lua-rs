#[test]
fn callback_qsort() {
    let cts = Rc::new(RefCell::new(CTState::new()));
    cdef(&mut cts.borrow_mut(), LIBC_DECLS).unwrap();
    let ptr_id = typeof_(&mut cts.borrow_mut(), "int (*)(const void *, const void *)").unwrap();
    let calls = Rc::new(RefCell::new(0));
    let weak = Rc::downgrade(&cts);
    let calls2 = calls.clone();
    let handler = Rc::new(move |frame: &mut CallbackFrame| {
        let cts = weak.upgrade().unwrap();
        let cts = cts.borrow();
        let fid = cts.cb.cbid(frame.slot);
        let args = frame.args(&cts, fid);
        assert_eq!(args.len(), 2);
        assert!(args.iter().all(|a| ctype_isptr(cts.get(a.ctid).info)));
        // SAFETY: both arguments are `const void *` pointing to ints of the array.
        let (a, b) = unsafe {
            let pa = *(args[0].ptr as *const *const i32);
            let pb = *(args[1].ptr as *const *const i32);
            (*pa, *pb)
        };
        *calls2.borrow_mut() += 1;
        let r: i32 = (a > b) as i32 - (a < b) as i32;
        frame.set_result(&cts, cts.child(fid), &r.to_ne_bytes());
    });
    let cbptr = callback_new(&mut cts.borrow_mut(), ptr_id, Some(handler))
        .unwrap()
        .unwrap();
    assert_eq!(cts.borrow().cb.ptr2slot(cbptr), 0);

    let mut data: Vec<i32> = vec![5, -3, 99, 0, 42, -100, 7, 7, 1, 2];
    let mut cc = {
        let mut c = cts.borrow_mut();
        let id = c.getname(b"qsort", 1 << CT_FUNC);
        CCallState::new(
            &mut c,
            id,
            libc_sym("qsort"),
            &mut Args(vec![
                A::P(data.as_mut_ptr().cast()),
                A::I(data.len() as i64),
                A::I(4),
                A::P(cbptr),
            ]),
        )
        .unwrap()
    };
    // SAFETY: qsort is declared correctly and the callback compares ints.
    unsafe { cc.call() };
    assert_eq!(data, vec![-100, -3, 0, 1, 2, 5, 7, 7, 42, 99]);
    assert!(*calls.borrow() >= 9);
    assert_eq!(cc.result(&cts.borrow()), CCallResult::Void);
    assert_eq!(cts.borrow().cb.slot(), 0);
}

