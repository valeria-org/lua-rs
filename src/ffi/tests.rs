    // 16 byte struct returned in rax:rdx.
    let (mut cc, _) = call(
        &mut cts,
        "ldiv",
        libc_sym("ldiv"),
        vec![A::I(1 << 40), A::I(-7)],
    )
    .unwrap();
    match cc.result(&cts) {
        CCallResult::Aggregate { bytes, .. } => {
            assert_eq!(
                i64::from_ne_bytes(bytes[0..8].try_into().unwrap()),
                (1i64 << 40) / -7
            );
            assert_eq!(
                i64::from_ne_bytes(bytes[8..16].try_into().unwrap()),
                (1i64 << 40) % -7
            );
        }
        r => panic!("{r:?}"),
    }

    // Double in and out, mixed with an int register argument.
    let (mut cc, _) = call(
        &mut cts,
        "ldexp",
        libc_sym("ldexp"),
        vec![A::D(1.5), A::I(10)],
    )
    .unwrap();
    assert_eq!(scalar_f64(cc.result(&cts)), 1536.0);
    let (mut cc, _) = call(&mut cts, "fabsf", libm_sym("fabsf"), vec![A::D(-2.25)]).unwrap();
    assert_eq!(scalar_f64(cc.result(&cts)), 2.25);
    let (mut cc, _) = call(
        &mut cts,
        "strtod",
        libc_sym("strtod"),
        vec![A::S(c"  -12.5e3xyz"), A::P(std::ptr::null())],
    )
    .unwrap();
    assert_eq!(scalar_f64(cc.result(&cts)), -12500.0);

    // __asm__ redirect resolved through the C library namespace.
