    assert_eq!(msg(e), "wrong number of type parameters");
    let e = cparse(&mut cts, b"int [$]", abs, Some(&[CParam::Other(2)])).unwrap_err();
    assert_eq!(
        e,
        FfiError::ArgType {
            narg: 2,
            expected: "type parameter"
        }
    );
