#[test]
fn callback_args_and_results() {
    let cts = Rc::new(RefCell::new(CTState::new()));
    cdef(
        &mut cts.borrow_mut(),
        "typedef double (*cb_t)(int, double, int64_t, float, int8_t, uint16_t, int, int, int, double, int64_t);\
         double call_cb(cb_t cb); typedef char (*cbc_t)(int); int call_cb_char(cbc_t cb);",
    )
    .unwrap();
    let ptr_id = cts.borrow().getname(b"cb_t", 1 << CT_TYPEDEF);
    let ptr_id = cts.borrow().child(ptr_id);
    let weak = Rc::downgrade(&cts);
    let handler = Rc::new(move |frame: &mut CallbackFrame| {
        let cts = weak.upgrade().unwrap();
        let cts = cts.borrow();
        let fid = cts.cb.cbid(frame.slot);
        let mut sum = 0.0;
        for (i, a) in frame.args(&cts, fid).iter().enumerate() {
            let ct = *cts.get(a.ctid);
            // SAFETY: each pointer refers to an argument slot of at least ct.size bytes.
            let v = unsafe {
                if ctype_isfp(ct.info) {
                    if ct.size == 8 {
                        *(a.ptr as *const f64)
                    } else {
                        *(a.ptr as *const f32) as f64
                    }
                } else {
                    match (ct.size, ct.info & CTF_UNSIGNED != 0) {
                        (1, _) => *(a.ptr as *const i8) as f64,
                        (2, true) => *(a.ptr as *const u16) as f64,
                        (4, _) => *(a.ptr as *const i32) as f64,
                        _ => *(a.ptr as *const i64) as f64,
                    }
                }
            };
            sum += v * (i + 1) as f64;
        }
        frame.set_result(&cts, cts.child(fid), &sum.to_ne_bytes());
    });
    let cb = callback_new(&mut cts.borrow_mut(), ptr_id, Some(handler))
        .unwrap()
        .unwrap();
    let mut cc = {
        let mut c = cts.borrow_mut();
        let id = c.getname(b"call_cb", 1 << CT_FUNC);
        CCallState::new(
            &mut c,
            id,
            call_cb as *const c_void,
            &mut Args(vec![A::P(cb)]),
        )
        .unwrap()
    };
    // SAFETY: call_cb matches its declaration.
    unsafe { cc.call() };
    let expect = 1.0
        + 2.0 * 2.5
        + 3.0 * -3.0
        + 4.0 * 4.5
        + 5.0 * -5.0
        + 6.0 * 60000.0
        + 7.0 * 7.0
        + 8.0 * 8.0
        + 9.0 * 9.0
        + 10.0 * 10.5
        + 11.0 * (1i64 << 40) as f64;
    assert_eq!(scalar_f64(cc.result(&cts.borrow())), expect);

    // Narrow integer results are sign-extended.
    let ptr_id = {
        let c = cts.borrow();
        c.child(c.getname(b"cbc_t", 1 << CT_TYPEDEF))
    };
    let weak = Rc::downgrade(&cts);
    let handler = Rc::new(move |frame: &mut CallbackFrame| {
        let cts = weak.upgrade().unwrap();
        let cts = cts.borrow();
        let fid = cts.cb.cbid(frame.slot);
        let x = frame.gpr[0] as i32;
        frame.set_result(&cts, cts.child(fid), &[(x as u8).wrapping_neg()]);
    });
    let cb2 = callback_new(&mut cts.borrow_mut(), ptr_id, Some(handler))
        .unwrap()
        .unwrap();
    assert_eq!(cts.borrow().cb.ptr2slot(cb2), 1);
    let mut cc = {
        let mut c = cts.borrow_mut();
        let id = c.getname(b"call_cb_char", 1 << CT_FUNC);
        CCallState::new(
            &mut c,
            id,
            call_cb_char as *const c_void,
            &mut Args(vec![A::P(cb2)]),
        )
        .unwrap()
    };
    // SAFETY: call_cb_char matches its declaration.
    unsafe { cc.call() };
    assert_eq!(scalar_i64(cc.result(&cts.borrow())), -44);
}

#[test]
fn callback_slots() {
    let mut cts = CTState::new();
    let ok = typeof_(&mut cts, "void (*)(int, double)").unwrap();
    let bad = [
        "int (*)(int, ...)",
        "struct { int x; } (*)(void)",
        "void (*)(struct { int x; })",
        "long double (*)(void)",
        "int",
        "int *",
    ]
    .map(|s| typeof_(&mut cts, s).unwrap());
    for b in bad {
        assert_eq!(
            callback_new(&mut cts, b, None),
            Ok(None),
            "{}",
            tostring(&cts, b)
        );
    }
    let p0 = callback_new(&mut cts, ok, None).unwrap().unwrap();
    let p1 = callback_new(&mut cts, ok, None).unwrap().unwrap();
    assert_eq!(cts.cb.ptr2slot(p0), 0);
    assert_eq!(cts.cb.ptr2slot(p1), 1);
    assert_eq!(cts.cb.ptr2slot(p0.wrapping_byte_add(1)), !0);
    cts.cb.free(0);
    assert_eq!(cts.cb.cbid(0), 0);
    let p2 = callback_new(&mut cts, ok, None).unwrap().unwrap();
    assert_eq!(p2, p0);
    let mut n = 3;
    loop {
        match callback_new(&mut cts, ok, None) {
            Ok(Some(_)) => n += 1,
            Err(e) => {
                assert_eq!(msg(e), "too many callbacks");
                break;
            }
            Ok(None) => unreachable!(),
        }
    }
    // Reference: the 897th callback fails.
    assert_eq!(n, 897);
}

