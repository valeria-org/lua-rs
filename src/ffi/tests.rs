/// Test argument values (stand-ins for Lua values).
#[derive(Clone)]
enum A {
    I(i64),
    D(f64),
    P(*const c_void),
    S(&'static CStr),
    Raw(Vec<u8>),
}

struct Args(Vec<A>);

impl CCallArgs for Args {
    type Error = FfiError;

    fn count(&self) -> usize {
        self.0.len()
    }

    fn vararg_ctid(&mut self, _cts: &mut CTState, narg: usize) -> Result<CTypeID, FfiError> {
        Ok(match self.0[narg - 1] {
            A::I(_) => CTID_INT64,
            A::D(_) => ccall::CTID_VARARG_NUMBER,
            A::P(_) => ccall::CTID_VARARG_OTHER,
            A::S(_) => ccall::CTID_VARARG_STRING,
            A::Raw(_) => return Err(FfiError::Caller(b"bad vararg".to_vec())),
        })
    }

    fn convert(
        &mut self,
        cts: &mut CTState,
        narg: usize,
        did: CTypeID,
        dst: &mut [u8],
    ) -> Result<(), FfiError> {
        let ct = *cts.get(did);
        let a = &self.0[narg - 1];
        assert_eq!(dst.len(), ct.size as usize);
        let bad = || FfiError::Caller(format!("cannot convert arg {narg}").into_bytes());
        if ctype_isfp(ct.info) {
            let v = match a {
                A::D(d) => *d,
                A::I(i) => *i as f64,
                _ => return Err(bad()),
            };
            if ct.size == 4 {
                dst.copy_from_slice(&(v as f32).to_ne_bytes());
            } else {
                dst.copy_from_slice(&v.to_ne_bytes());
            }
        } else if ctype_isnum(ct.info) || ctype_isenum(ct.info) {
            let v = match a {
                A::I(i) => *i,
                A::D(d) => *d as i64,
                _ => return Err(bad()),
            };
            dst.copy_from_slice(&v.to_ne_bytes()[..ct.size as usize]);
        } else if ctype_isptr(ct.info) {
            let p = match a {
                A::P(p) => *p as usize,
                A::S(s) => s.as_ptr() as usize,
                _ => return Err(bad()),
            };
            dst.copy_from_slice(&p.to_ne_bytes());
        } else {
            match a {
                A::Raw(b) => dst.copy_from_slice(b),
                _ => return Err(bad()),
            }
        }
        Ok(())
    }
}

/// Declare `decl` in the C namespace, then call `name` at `fptr`.
fn call(
    cts: &mut CTState,
    name: &str,
    fptr: *const c_void,
    args: Vec<A>,
) -> Result<(CCallState, CTypeID), FfiError> {
    let id = cts.getname(name.as_bytes(), 1 << CT_FUNC);
    assert!(id != 0, "{name} not declared");
    let (fid, psz) = ccall::func_type(cts, id).unwrap();
    assert_eq!(psz, CTSIZE_PTR);
    let mut cc = CCallState::new(cts, fid, fptr, &mut Args(args))?;
    // SAFETY: the declarations match the called functions.
    unsafe { cc.call() };
    Ok((cc, fid))
}

fn libc_sym(name: &str) -> *const c_void {
    CLibrary::default_namespace().sym(name.as_bytes()).unwrap()
}

fn libm_sym(name: &str) -> *const c_void {
    let libm = CLibrary::load(b"m", false).unwrap();
    let p = libm.sym(name.as_bytes()).unwrap();
    std::mem::forget(libm); // Keep the library loaded.
    p
}

fn scalar_i64(r: CCallResult<'_>) -> i64 {
    match r {
        CCallResult::Scalar { bytes, .. } => {
            let mut b = [0u8; 8];
            b[..bytes.len()].copy_from_slice(bytes);
            let v = i64::from_ne_bytes(b);
            let shift = 64 - 8 * bytes.len() as u32;
            (v << shift) >> shift
        }
        r => panic!("unexpected result {r:?}"),
    }
}

fn scalar_f64(r: CCallResult<'_>) -> f64 {
    match r {
        CCallResult::Scalar { bytes, .. } if bytes.len() == 8 => {
            f64::from_ne_bytes(bytes.try_into().unwrap())
        }
        CCallResult::Scalar { bytes, .. } => f32::from_ne_bytes(bytes.try_into().unwrap()) as f64,
        r => panic!("unexpected result {r:?}"),
    }
}

