/// `luaopen_jit`.
pub fn open_jit(vm: &mut Vm) -> LuaResult<()> {
    // lib_create_table(L, "jit", 10) as generated in lj_libdef.h.
    let loaded = super::loaded_table(vm);
    let k = vm.new_str(b"jit");
    if !matches!(loaded.get_str(k), Value::Table(_)) {
        let g = vm.cur_thread.env();
        let Some(t) = super::package::find_table(vm, g, b"jit", 10)? else {
            let m = crate::vm::fmt_msg(ErrMsg::BADMODN, &[b"jit"]);
            return Err(vm.err_callermsg(&m));
        };
        loaded
            .set_str(k, Value::Table(t))
            .map_err(|e| vm.tab_error(e))?;
    }
    let funcs: &[LibFn] = &[
        ("on", lj_cf_jit_on, FF_JIT_ON),
        ("off", lj_cf_jit_off, FF_JIT_OFF),
        ("flush", lj_cf_jit_flush, FF_JIT_FLUSH),
        ("status", lj_cf_jit_status, FF_JIT_STATUS),
        ("security", lj_cf_jit_security, FF_JIT_SECURITY),
        ("attach", lj_cf_jit_attach, FF_JIT_ATTACH),
    ];
    let t = register_lib(vm, "jit", funcs)?;
    let os = Value::Str(vm.new_str(LJ_OS_NAME.as_bytes()));
    let arch = Value::Str(vm.new_str(LJ_ARCH_NAME.as_bytes()));
    let ver = Value::Str(vm.new_str(LUAJIT_VERSION.as_bytes()));
    for (k, v) in [
        ("os", os),
        ("arch", arch),
        ("version_num", Value::Num(LUAJIT_VERSION_NUM as f64)),
        ("version", ver),
    ] {
        let k = vm.new_str(k.as_bytes());
        t.set_str(k, v).map_err(|e| vm.tab_error(e))?;
    }
    prereg(vm, b"jit.profile", luaopen_jit_profile)?;
    prereg(vm, b"jit.util", luaopen_jit_util)?;
    Ok(())
}

/// `lj_lib_prereg`: `package.preload[name] = f` (environment: the globals).
fn prereg(vm: &mut Vm, name: &[u8], f: crate::func::NativeFn) -> LuaResult<()> {
    let reg = vm.registry;
    let pre = super::package::find_table(vm, reg, b"_PRELOAD", 4)?.expect("registry._PRELOAD");
    let env = vm.cur_thread.env();
    let f = vm.new_native(NativeImpl::Rust(f), FF_C, vec![], env);
    let k = vm.new_str(name);
    pre.set_str(k, Value::Func(f))
        .map_err(|e| vm.tab_error(e))?;
    Ok(())
}

/// `LJ_LIB_REG(L, NULL, name)`: a fresh table with the given functions.
fn new_module(vm: &mut Vm, hsize: u32, funcs: &[LibFn]) -> LuaResult<Gc<Table>> {
    let t = vm.new_table(0, crate::table::hsize2hbits(hsize))?;
    for &(name, f, ffid) in funcs {
        let f = super::new_lib_fn(vm, f, ffid, vec![]);
        let k = vm.new_str(name.as_bytes());
        t.set_str(k, Value::Func(f)).map_err(|e| vm.tab_error(e))?;
    }
    Ok(t)
}

fn luaopen_jit_util(vm: &mut Vm) -> LuaResult<usize> {
    let funcs: &[LibFn] = &[
        ("funcinfo", lj_cf_jit_util_funcinfo, FF_JIT_UTIL_FUNCINFO),
        ("funcbc", lj_cf_jit_util_funcbc, FF_JIT_UTIL_FUNCBC),
        ("funck", lj_cf_jit_util_funck, FF_JIT_UTIL_FUNCK),
        (
            "funcuvname",
            lj_cf_jit_util_funcuvname,
            FF_JIT_UTIL_FUNCUVNAME,
        ),
    ];
    let t = new_module(vm, 4, funcs)?;
    vm.ret1(Value::Table(t))
}

fn luaopen_jit_profile(vm: &mut Vm) -> LuaResult<usize> {
    let funcs: &[LibFn] = &[
        ("start", lj_cf_jit_profile_start, FF_JIT_PROFILE_START),
        ("stop", lj_cf_jit_profile_stop, FF_JIT_PROFILE_STOP),
        (
            "dumpstack",
            lj_cf_jit_profile_dumpstack,
            FF_JIT_PROFILE_DUMPSTACK,
        ),
    ];
    let t = new_module(vm, 3, funcs)?;
    vm.ret1(Value::Table(t))
}

// -- jit.* functions ----------------------------------------------------------------------------

const LUAJIT_MODE_ENGINE: i32 = 0;
const LUAJIT_MODE_FUNC: i32 = 2;
const LUAJIT_MODE_ALLFUNC: i32 = 3;
const LUAJIT_MODE_ALLSUBFUNC: i32 = 4;
const LUAJIT_MODE_MASK: i32 = 0x00ff;
const LUAJIT_MODE_OFF: i32 = 0x0000;
const LUAJIT_MODE_ON: i32 = 0x0100;
const LUAJIT_MODE_FLUSH: i32 = 0x0200;

/// `luaJIT_setmode` of a build without the JIT compiler: engine and function modes can only
/// be turned off or flushed.
fn luajit_setmode(vm: &mut Vm, mode: i32) -> LuaResult<bool> {
    if vm.rt.in_finalizers {
        return Err(vm.err_caller(ErrMsg::NOGCMM));
    }
    Ok(match mode & LUAJIT_MODE_MASK {
        LUAJIT_MODE_ENGINE | LUAJIT_MODE_FUNC | LUAJIT_MODE_ALLFUNC | LUAJIT_MODE_ALLSUBFUNC => {
            mode & LUAJIT_MODE_ON == 0
        }
        _ => false,
    })
}

/// `setjitmode`.
fn setjitmode(vm: &mut Vm, mut mode: i32) -> LuaResult<usize> {
    let a1 = vm.arg(1);
    if vm.nargs() == 0 || a1.is_nil() {
        mode |= LUAJIT_MODE_ENGINE;
    } else {
        if !matches!(a1, Value::Func(_) | Value::Proto(_) | Value::Bool(true)) {
            return Err(vm.argt_error(1, "function"));
        }
        mode |= match vm.arg(2) {
            Value::Bool(b) if vm.nargs() >= 2 => {
                if b {
                    LUAJIT_MODE_ALLFUNC
                } else {
                    LUAJIT_MODE_ALLSUBFUNC
                }
            }
            _ => LUAJIT_MODE_FUNC,
        };
    }
    if !luajit_setmode(vm, mode)? {
        if mode & LUAJIT_MODE_MASK == LUAJIT_MODE_ENGINE {
            return Err(vm.err_caller(ErrMsg::NOJIT));
        }
        return Err(vm.argt_error(1, "function"));
    }
    Ok(0)
}

fn lj_cf_jit_on(vm: &mut Vm) -> LuaResult<usize> {
    setjitmode(vm, LUAJIT_MODE_ON)
}

fn lj_cf_jit_off(vm: &mut Vm) -> LuaResult<usize> {
    setjitmode(vm, LUAJIT_MODE_OFF)
}

fn lj_cf_jit_flush(vm: &mut Vm) -> LuaResult<usize> {
    setjitmode(vm, LUAJIT_MODE_FLUSH)
}

fn lj_cf_jit_status(vm: &mut Vm) -> LuaResult<usize> {
    vm.ret1(Value::Bool(false))
}

fn lj_cf_jit_security(vm: &mut Vm) -> LuaResult<usize> {
    let idx = vm.check_opt(1, -1, &["prng", "strhash", "strid", "mcode"])?;
    vm.ret1(Value::Num(((LJ_SECURITY_MODE >> (2 * idx)) & 3) as f64))
}

fn lj_cf_jit_attach(vm: &mut Vm) -> LuaResult<usize> {
    let f = vm.check_func(1)?;
    let s = vm.opt_str(2)?;
    let reg = vm.registry;
    let Some(t) = super::package::find_table(
        vm,
        reg,
        crate::vm::VMEVENTS_REGKEY.as_bytes(),
        LJ_VMEVENTS_HSIZE,
    )?
    else {
        return Ok(0);
    };
    vm.push(Value::Table(t));
    match s {
        Some(s) => {
            let idx = vmevent_hash(s.as_bytes());
            t.set_int(idx, Value::Func(f))
                .map_err(|e| vm.tab_error(e))?;
        }
        None => {
            let mut k = Value::Nil;
            while let Some((nk, v)) = t.next(k).map_err(|e| vm.tab_error(e))? {
                if let Value::Func(g) = v
                    && g == f
                {
                    t.set(nk, Value::Nil).map_err(|e| vm.tab_error(e))?;
                }
                k = nk;
            }
        }
    }
    Ok(0)
}

