/// `lj_lib_checkLproto`: prototype of a Lua function or proto argument; `None` for other
/// functions if `nolua`.
fn check_lproto(vm: &mut Vm, narg: usize, nolua: bool) -> LuaResult<Option<Gc<Proto>>> {
    if narg <= vm.nargs() {
        match vm.arg(narg) {
            Value::Proto(p) => return Ok(Some(p)),
            Value::Func(f) => match f.proto() {
                Some(p) => return Ok(Some(p)),
                None if nolua => return Ok(None),
                None => {}
            },
            _ => {}
        }
    }
    Err(vm.argt_error(narg, "function"))
}

fn setintfield(vm: &mut Vm, t: Gc<Table>, name: &str, v: f64) -> LuaResult<()> {
    let k = vm.new_str(name.as_bytes());
    t.set_str(k, Value::Num(v)).map_err(|e| vm.tab_error(e))
}

fn setfield(vm: &mut Vm, t: Gc<Table>, name: &str, v: Value) -> LuaResult<()> {
    let k = vm.new_str(name.as_bytes());
    vm.setindex(Value::Table(t), Value::Str(k), v)
}

/// `lj_debug_pushloc`: short location `chunk:line` of `pt` at `pc`.
pub fn proto_loc(pt: &Gc<Proto>, pc: u32) -> Vec<u8> {
    let name = pt.chunkname.as_bytes();
    let s = cstr(name);
    let line = debug_line(pt, pc);
    let mut out = Vec::new();
    if pt.firstline == u32::MAX {
        out.extend_from_slice(b"builtin:");
        out.extend_from_slice(s);
    } else if name.first() == Some(&b'@') {
        let mut p = &name[1..];
        let len = p.len();
        for i in (1..=len).rev() {
            let c = if i < len { p[i] } else { 0 };
            if c == b'/' || c == b'\\' {
                p = &p[i + 1..];
                break;
            }
        }
        out.extend_from_slice(cstr(p));
        out.extend_from_slice(format!(":{line}").as_bytes());
    } else if name.len() > 40 {
        crate::text::strfmt::put_ptr(&mut out, pt.addr());
        out.extend_from_slice(format!(":{line}").as_bytes());
    } else if name.first() == Some(&b'=') {
        out.extend_from_slice(cstr(&name[1..]));
        out.extend_from_slice(format!(":{line}").as_bytes());
    } else {
        out.push(b'"');
        out.extend_from_slice(s);
        out.extend_from_slice(format!("\":{line}").as_bytes());
    }
    out
}

fn lj_cf_jit_util_funcinfo(vm: &mut Vm) -> LuaResult<usize> {
    match check_lproto(vm, 1, true)? {
        Some(pt) => {
            let pc = vm.opt_int(2, 0)? as u32;
            let t = vm.new_table(0, crate::table::hsize2hbits(16))?;
            vm.push(Value::Table(t));
            setintfield(vm, t, "linedefined", pt.firstline as f64)?;
            setintfield(
                vm,
                t,
                "lastlinedefined",
                pt.firstline.wrapping_add(pt.numline) as i32 as f64,
            )?;
            setintfield(vm, t, "stackslots", pt.framesize as f64)?;
            setintfield(vm, t, "params", pt.numparams as f64)?;
            setintfield(vm, t, "bytecodes", pt.bc.len() as f64)?;
            setintfield(vm, t, "gcconsts", pt.kgc.len() as f64)?;
            setintfield(vm, t, "nconsts", pt.knum.len() as f64)?;
            setintfield(vm, t, "upvalues", pt.sizeuv() as f64)?;
            if (pc as usize) < pt.bc.len() {
                setintfield(vm, t, "currentline", debug_line(&pt, pc) as f64)?;
            }
            setfield(
                vm,
                t,
                "isvararg",
                Value::Bool(pt.flags() & PROTO_VARARG != 0),
            )?;
            setfield(
                vm,
                t,
                "children",
                Value::Bool(pt.flags() & PROTO_CHILD != 0),
            )?;
            setfield(vm, t, "source", Value::Str(pt.chunkname))?;
            let loc = proto_loc(&pt, pc);
            let loc = Value::Str(vm.new_str(&loc));
            setfield(vm, t, "loc", loc)?;
            let k = vm.new_str(b"proto");
            t.set_str(k, Value::Proto(pt))
                .map_err(|e| vm.tab_error(e))?;
            Ok(1)
        }
        None => {
            let Value::Func(f) = vm.arg(1) else {
                unreachable!("checked function")
            };
            let t = vm.new_table(0, crate::table::hsize2hbits(4))?;
            vm.push(Value::Table(t));
            if f.ffid() != FF_C {
                setintfield(vm, t, "ffid", f.ffid() as f64)?;
            }
            setintfield(vm, t, "addr", native_addr(&f) as isize as f64)?;
            setintfield(vm, t, "upvalues", f.nupvalues() as f64)?;
            Ok(1)
        }
    }
}

fn lj_cf_jit_util_funcbc(vm: &mut Vm) -> LuaResult<usize> {
    let pt = check_lproto(vm, 1, false)?.expect("Lua proto");
    let pc = vm.check_int(2)? as u32 as usize;
    if pc < pt.bc.len() {
        let ins = pt.bc[pc];
        let op = Op::from_u8(ins.op_byte()).expect("valid opcode");
        vm.push(Value::Num(ins.0 as i32 as f64));
        vm.push(Value::Num(op.mode() as f64));
        return Ok(2);
    }
    Ok(0)
}

fn lj_cf_jit_util_funck(vm: &mut Vm) -> LuaResult<usize> {
    let pt = check_lproto(vm, 1, false)?.expect("Lua proto");
    let idx = vm.check_int(2)?;
    if idx >= 0 {
        if (idx as usize) < pt.knum.len() {
            return vm.ret1(Value::Num(pt.knum[idx as usize]));
        }
    } else {
        let i = !idx as usize;
        if i < pt.kgc.len() {
            let v = match &pt.kgc[i] {
                KGc::Str(s) => Value::Str(*s),
                KGc::Proto(p) => Value::Proto(*p),
                KGc::Table(t) => Value::Table(*t),
                KGc::CData(c) => Value::CData(*c),
            };
            return vm.ret1(v);
        }
    }
    Ok(0)
}

fn lj_cf_jit_util_funcuvname(vm: &mut Vm) -> LuaResult<usize> {
    let pt = check_lproto(vm, 1, false)?.expect("Lua proto");
    let idx = vm.check_int(2)? as u32 as usize;
    if idx < pt.sizeuv() {
        let n = crate::vm::debug::uvname(&pt, idx);
        let s = vm.new_str(cstr(&n));
        return vm.ret1(Value::Str(s));
    }
    Ok(0)
}

// -- Profiler (lj_profile.c, SIGPROF variant) ---------------------------------------------------

/// Profiler callback (`luaJIT_profile_callback`): called with the profiled thread current,
/// the number of samples since the last call and the sampled VM state (`'I'` interpreter,
/// `'C'` native code, `'G'` garbage collector).
pub type ProfileCallback = Box<dyn FnMut(&mut Vm, i32, u8)>;

/// `LJ_PROFILE_INTERVAL_DEFAULT` (milliseconds).
const LJ_PROFILE_INTERVAL_DEFAULT: i32 = 10;

/// Identity of the VM running the profiler (`ps->g`), 0 if none.
static PROF_OWNER: AtomicUsize = AtomicUsize::new(0);
/// Samples since the last callback (`ps->samples`).
static PROF_SAMPLES: AtomicI32 = AtomicI32::new(0);
/// VM state when the timer last armed the hook (`ps->vmstate`).
static PROF_VMSTATE: AtomicU8 = AtomicU8::new(b'I');
/// Timer is running.
static PROF_RUNNING: AtomicBool = AtomicBool::new(false);
/// Previous SIGPROF disposition (`ps->oldsa`).
static PROF_OLDSA: Mutex<Option<libc::sigaction>> = Mutex::new(None);

thread_local! {
    /// The callback of the running profiler (`ps->cb`, `ps->data`).
    static PROF_CB: RefCell<Option<ProfileCallback>> = const { RefCell::new(None) };
}

fn vm_id(vm: &Vm) -> usize {
    vm as *const Vm as usize
}

/// `profile_trigger` (from the SIGPROF handler): count the sample and arm the hook.
extern "C" fn profile_signal(_sig: libc::c_int) {
    PROF_SAMPLES.fetch_add(1, Ordering::Relaxed);
    if !PROFILE_PENDING.load(Ordering::Relaxed) {
        PROF_VMSTATE.store(VMSTATE.load(Ordering::Relaxed), Ordering::Relaxed);
        PROFILE_PENDING.store(true, Ordering::Relaxed);
    }
}

/// `profile_timer_start`.
fn profile_timer_start(interval: i32) {
    // SAFETY: plain libc calls with initialized structs; the handler only touches atomics.
    unsafe {
        let tv = libc::timeval {
            tv_sec: (interval / 1000) as libc::time_t,
            tv_usec: ((interval % 1000) * 1000) as libc::suseconds_t,
        };
        let tm = libc::itimerval {
            it_interval: tv,
            it_value: tv,
        };
        libc::setitimer(libc::ITIMER_PROF, &tm, std::ptr::null_mut());
        let mut sa: libc::sigaction = std::mem::zeroed();
        sa.sa_flags = libc::SA_RESTART;
        sa.sa_sigaction = profile_signal as extern "C" fn(libc::c_int) as libc::sighandler_t;
        libc::sigemptyset(&mut sa.sa_mask);
        let mut old: libc::sigaction = std::mem::zeroed();
        libc::sigaction(libc::SIGPROF, &sa, &mut old);
        *PROF_OLDSA.lock().unwrap_or_else(|e| e.into_inner()) = Some(old);
    }
    PROF_RUNNING.store(true, Ordering::Relaxed);
}

/// `profile_timer_stop`.
fn profile_timer_stop() {
    if !PROF_RUNNING.swap(false, Ordering::Relaxed) {
        return;
    }
    // SAFETY: see `profile_timer_start`.
    unsafe {
        let tv = libc::timeval {
            tv_sec: 0,
            tv_usec: 0,
        };
        let tm = libc::itimerval {
            it_interval: tv,
            it_value: tv,
        };
        libc::setitimer(libc::ITIMER_PROF, &tm, std::ptr::null_mut());
        if let Some(old) = PROF_OLDSA.lock().unwrap_or_else(|e| e.into_inner()).take() {
            libc::sigaction(libc::SIGPROF, &old, std::ptr::null_mut());
        }
    }
}

/// `lj_profile_interpreter`: deliver the pending samples to the callback, with hooks, VM
/// events and further profiler callbacks disabled.
fn profile_interpreter(vm: &mut Vm) -> LuaResult<()> {
    let samples = PROF_SAMPLES.swap(0, Ordering::Relaxed);
    let vmstate = PROF_VMSTATE.load(Ordering::Relaxed);
    let Some(mut cb) = PROF_CB.with(|c| c.borrow_mut().take()) else {
        return Ok(());
    };
    let (oldh, oldev) = (vm.rt.hook.active, vm.rt.hook.vmevent);
    vm.rt.hook.active = true;
    vm.rt.hook.vmevent = true;
    cb(vm, samples, vmstate);
    vm.rt.hook.active = oldh;
    vm.rt.hook.vmevent = oldev;
    // Keep the callback unless the profiler was stopped or restarted meanwhile.
    if PROF_OWNER.load(Ordering::Relaxed) == vm_id(vm) {
        PROF_CB.with(|c| {
            let mut c = c.borrow_mut();
            if c.is_none() {
                *c = Some(cb);
            }
        });
    }
    Ok(())
}

/// `luaJIT_profile_start`: mode chars `i<ms>` (interval); others are ignored without a JIT.
pub fn profile_start(vm: &mut Vm, mode: &[u8], cb: ProfileCallback) {
    let mut interval = LJ_PROFILE_INTERVAL_DEFAULT;
    let mode = cstr(mode);
    let mut i = 0;
    while i < mode.len() {
        let m = mode[i];
        i += 1;
        if m == b'i' {
            interval = 0;
            while i < mode.len() && mode[i].is_ascii_digit() {
                interval = interval
                    .wrapping_mul(10)
                    .wrapping_add((mode[i] - b'0') as i32);
                i += 1;
            }
            if interval <= 0 {
                interval = 1;
            }
        }
    }
    if PROF_OWNER.load(Ordering::Relaxed) != 0 {
        profile_stop(vm);
        if PROF_OWNER.load(Ordering::Relaxed) != 0 {
            return; // Profiler in use by another VM.
        }
    }
    PROF_OWNER.store(vm_id(vm), Ordering::Relaxed);
    PROF_SAMPLES.store(0, Ordering::Relaxed);
    PROF_CB.with(|c| *c.borrow_mut() = Some(cb));
    vm.set_profile_handler(Some(profile_interpreter));
    profile_timer_start(interval);
}

/// `luaJIT_profile_stop`: only stops a profiler started by this VM.
pub fn profile_stop(vm: &mut Vm) {
    if PROF_OWNER.load(Ordering::Relaxed) != vm_id(vm) {
        return;
    }
    PROF_OWNER.store(0, Ordering::Relaxed);
    profile_timer_stop();
    vm.set_profile_handler(None);
    PROF_CB.with(|c| *c.borrow_mut() = None);
}

/// `debug_putchunkname`.
fn putchunkname(sb: &mut Vec<u8>, pt: &Proto, pathstrip: bool) -> bool {
    let name = pt.chunkname.as_bytes();
    if pt.firstline == u32::MAX {
        sb.extend_from_slice(b"[builtin:");
        sb.extend_from_slice(name);
        sb.push(b']');
        return false;
    }
    if matches!(name.first(), Some(b'=' | b'@')) {
        let mut p = &name[1..];
        if pathstrip && let Some(i) = p.iter().rposition(|&c| c == b'/' || c == b'\\') {
            p = &p[i + 1..];
        }
        sb.extend_from_slice(p);
    } else {
        sb.extend_from_slice(b"[string]");
    }
    true
}

/// `lj_debug_dumpstack` / `luaJIT_profile_dumpstack`: compact stack dump of `th`.
pub fn profile_dumpstack(vm: &mut Vm, th: Gc<Thread>, fmt: &[u8], depth: i32) -> Vec<u8> {
    let fmt = cstr(fmt);
    let mut sb = Vec::new();
    let (mut level, mut depth, mut dir) = (0i32, depth, 1i32);
    let mut pathstrip = true;
    let mut lastlen = 0usize;
    if depth < 0 {
        level = !depth;
        depth = -1;
        dir = -1;
    }
    while level != depth {
        match vm.get_stack(th, level) {
            Some(fr) => {
                let f: Gc<Function> = th.frame(fr.idx).expect("frame").func;
                for &c in fmt {
                    match c {
                        b'p' => pathstrip = false,
                        b'F' | b'f' | b'l' => {
                            if c != b'l'
                                && let Some((_, name)) = funcname(vm, th, fr.idx)
                            {
                                if c == b'F'
                                    && let Some(pt) = f.proto()
                                    && pt.firstline != u32::MAX
                                {
                                    putchunkname(&mut sb, &pt, pathstrip);
                                    sb.push(b':');
                                }
                                sb.extend_from_slice(cstr(&name));
                                continue;
                            }
                            if let Some(pt) = f.proto() {
                                if putchunkname(&mut sb, &pt, pathstrip) {
                                    let line = if c == b'l' {
                                        frameline(th, fr.idx)
                                    } else {
                                        pt.firstline as i32
                                    };
                                    let line = if line >= 0 { line } else { pt.firstline as i32 };
                                    sb.push(b':');
                                    sb.extend_from_slice(line.to_string().as_bytes());
                                }
                            } else if f.is_builtin() {
                                sb.extend_from_slice(format!("[builtin#{}]", f.ffid()).as_bytes());
                            } else {
                                sb.push(b'@');
                                crate::text::strfmt::put_ptr(&mut sb, native_addr(&f));
                            }
                        }
                        b'Z' => lastlen = sb.len(),
                        _ => sb.push(c),
                    }
                }
            }
            None if dir == 1 => break,
            None => level = vm.stack_depth(th),
        }
        level += dir;
    }
    if lastlen != 0 {
        sb.truncate(lastlen);
    }
    sb
}

/// `KEY_PROFILE_THREAD`, `KEY_PROFILE_FUNC`: registry keys of the callback thread/function.
fn key_profile_thread() -> Value {
    Value::Num(f64::from_bits(0x8100_0000_0000_0000 | b't' as u64))
}
fn key_profile_func() -> Value {
    Value::Num(f64::from_bits(0x8100_0000_0000_0000 | b'f' as u64))
}

/// `jit_profile_callback`: call the Lua callback on the profiler thread as
/// `callback(thread, samples, vmstate)`; an error is fatal (panic message, exit).
fn jit_profile_callback(vm: &mut Vm, samples: i32, vmstate: u8) {
    let f = vm.registry.get(key_profile_func());
    let Value::Thread(l2) = vm.registry.get(key_profile_thread()) else {
        return;
    };
    if !matches!(f, Value::Func(_)) {
        return;
    }
    let l = vm.cur_thread;
    let st = vm.new_str(&[vmstate]);
    let top = l2.top();
    if l2.max_stack().saturating_sub(top) < crate::thread::LJ_STACK_MIN
        && vm.grow_stack(l2, crate::thread::LJ_STACK_MIN).is_err()
    {
        return;
    }
    l2.set(top, f);
    l2.set(top + 1, Value::Nil);
    l2.set(top + 2, Value::Thread(l));
    l2.set(top + 3, Value::Num(samples as f64));
    l2.set(top + 4, Value::Str(st));
    l2.set_top(top + 5);
    let oldstatus = l2.status();
    l2.set_status(ThreadStatus::Running);
    l.set_status(ThreadStatus::Normal);
    vm.cur_thread = l2;
    let r = vm.call_at(l2, top, 3, FrameKind::Cp(ErrFunc::None), 0);
    vm.cur_thread = l;
    l.set_status(ThreadStatus::Running);
    l2.set_status(oldstatus);
    l2.set_top(top);
    if let Err(e) = r {
        vm.rt_clear_thrown();
        let msg = vm.tostring_opt(e.value);
        let mut o = std::io::stderr();
        use std::io::Write;
        let _ = o.write_all(b"PANIC: unprotected error in call to Lua API (");
        let _ = o.write_all(msg.as_deref().map_or(&b"?"[..], cstr));
        let _ = o.write_all(b")\n");
        let _ = o.flush();
        // SAFETY: flush C stdio buffers and terminate like upstream's exit(EXIT_FAILURE).
        unsafe { libc::exit(libc::EXIT_FAILURE) };
    }
}

fn lj_cf_jit_profile_start(vm: &mut Vm) -> LuaResult<usize> {
    let mode = vm.opt_str(1)?;
    let f = vm.check_func(2)?;
    let env = vm.current_env();
    let l2 = vm.new_thread(env);
    vm.push(Value::Thread(l2));
    let reg = vm.registry;
    vm.rawset(reg, key_profile_thread(), Value::Thread(l2))?;
    vm.rawset(reg, key_profile_func(), Value::Func(f))?;
    let mode = mode.map(|s| s.as_bytes().to_vec()).unwrap_or_default();
    profile_start(vm, &mode, Box::new(jit_profile_callback));
    Ok(0)
}

fn lj_cf_jit_profile_stop(vm: &mut Vm) -> LuaResult<usize> {
    profile_stop(vm);
    let reg = vm.registry;
    vm.rawset(reg, key_profile_thread(), Value::Nil)?;
    vm.rawset(reg, key_profile_func(), Value::Nil)?;
    Ok(0)
}

fn lj_cf_jit_profile_dumpstack(vm: &mut Vm) -> LuaResult<usize> {
    let (th, arg) = match vm.arg(1) {
        Value::Thread(t) if vm.nargs() >= 1 => (t, 1),
        _ => (vm.cur_thread, 0),
    };
    let fmt = vm.check_str(arg + 1)?;
    let depth = vm.check_int(arg + 2)?;
    let s = profile_dumpstack(vm, th, fmt.as_bytes(), depth);
    vm.push_str(&s);
    Ok(1)
}
