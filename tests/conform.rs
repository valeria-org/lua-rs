//! Differential conformance corpus: tricky programs and command lines (error messages with
//! variable names, number formatting, patterns, coroutines with pcall and metamethods, syntax
//! extensions, io/os error returns, FFI conversions and errors, `lua_load` reader semantics,
//! `luajit -b` output formats, REPL transcripts), run with the `luajit` binary (argv[0] =
//! `luajit`) in a fresh temporary copy of `tests/fixtures/conform/src`.
//!
//! `tests/fixtures/conform/cases.txt` lists the cases (`name | KEY=VALUE,... | arguments`);
//! `<name>.stdin` is the standard input. `<name>.expected` holds stdout, then `--- stderr` plus
//! stderr if non-empty, then `--- exit <status>`, with every `0x<hex>` normalized to `0x?`. The
//! expectations are generated by `tests/fixtures/conform/gen.sh` with the reference binary.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/conform")
}

fn copy_dir(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).unwrap();
    for e in std::fs::read_dir(from).unwrap() {
        let e = e.unwrap();
        let p = e.path();
        if p.is_dir() {
            copy_dir(&p, &to.join(e.file_name()));
        } else {
            std::fs::copy(&p, to.join(e.file_name())).unwrap();
        }
    }
}

/// Replace every `0x<lowercase hex digits>` by `0x?` (as the generator's `sed` does).
fn normalize(s: &str) -> String {
    let mut r = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(p) = rest.find("0x") {
        r.push_str(&rest[..p + 2]);
        let after = &rest[p + 2..];
        let t = after.trim_start_matches(|c: char| c.is_ascii_hexdigit() && !c.is_ascii_uppercase());
        if t.len() != after.len() {
            r.push('?');
        }
        rest = t;
    }
    r.push_str(rest);
    r
}

fn run(name: &str, env: &str, args: &str) -> String {
    let tmp = std::env::temp_dir().join(format!("ljrs-conform-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    copy_dir(&fixture_dir().join("src"), &tmp.join("src"));
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_luajit"));
    {
        use std::os::unix::process::CommandExt;
        cmd.arg0("luajit");
    }
    cmd.args(args.split_whitespace())
        .current_dir(&tmp)
        .env_remove("LUA_INIT")
        .env_remove("LUA_PATH")
        .env_remove("LUA_CPATH");
    for kv in env.split(',').filter(|s| !s.is_empty()) {
        let (k, v) = kv.split_once('=').expect("KEY=VALUE");
        cmd.env(k, v);
    }
    let stdin = match std::fs::File::open(fixture_dir().join(format!("{name}.stdin"))) {
        Ok(f) => Stdio::from(f),
        Err(_) => Stdio::null(),
    };
    let out = cmd.stdin(stdin).output().unwrap();
    let _ = std::fs::remove_dir_all(&tmp);
    let mut s = String::from_utf8_lossy(&out.stdout).into_owned();
    if !out.stderr.is_empty() {
        s.push_str("--- stderr\n");
        s.push_str(&String::from_utf8_lossy(&out.stderr));
    }
    s.push_str(&format!("--- exit {}\n", out.status.code().unwrap_or(-1)));
    normalize(&s)
}

#[test]
fn corpus_matches_reference() {
    let cases = std::fs::read_to_string(fixture_dir().join("cases.txt")).unwrap();
    let mut failures = Vec::new();
    for line in cases.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
        let mut f = line.splitn(3, '|').map(str::trim);
        let (name, env, args) = (f.next().unwrap(), f.next().unwrap(), f.next().unwrap());
        let expected =
            String::from_utf8_lossy(&std::fs::read(fixture_dir().join(format!("{name}.expected"))).unwrap()).into_owned();
        let got = run(name, env, args);
        if got != expected {
            let first = got.lines().zip(expected.lines()).position(|(g, e)| g != e);
            let detail = match first {
                Some(i) => format!(
                    "line {}:\n  got:      {:?}\n  expected: {:?}",
                    i + 1,
                    got.lines().nth(i).unwrap(),
                    expected.lines().nth(i).unwrap()
                ),
                None => format!("output length differs ({} vs {} lines)", got.lines().count(), expected.lines().count()),
            };
            failures.push(format!("{name}: {detail}"));
        }
    }
    assert!(failures.is_empty(), "cases differing from the reference:\n{}", failures.join("\n"));
}
