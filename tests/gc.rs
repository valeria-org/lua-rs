//! Garbage collector tests: GC-heavy fixtures run in GC stress mode (`LUAJIT_RS_GCSTRESS=1`: a
//! full collection at every GC safe point; in debug builds freed objects are quarantined, so a
//! use after free panics instead of reading reused memory), reachability details observable
//! through weak tables and finalizers, and collector pacing.
//!
//! Each case runs the `luajit` binary (argv[0] = `luajit`) on `tests/fixtures/gc/<name>.lua`
//! with that directory as cwd and compares with `<name>.expected`: stdout, then `--- stderr`
//! plus stderr if non-empty, then `--- exit <status>`, with every `0x<hex>` normalized to `0x?`.
//! The expectations are generated by `tests/fixtures/gc/gen.sh` with the reference binary,
//! which has no stress mode: the fixtures are written so that their output does not depend on
//! when collections happen.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/gc")
}

/// Replace every `0x<lowercase hex digits>` by `0x?` (as the generator's `sed` does).
fn normalize(s: &str) -> String {
    let mut r = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(p) = rest.find("0x") {
        r.push_str(&rest[..p + 2]);
        let after = &rest[p + 2..];
        let t = after.trim_start_matches(|c: char| c.is_ascii_hexdigit() && !c.is_ascii_uppercase());
        if t.len() != after.len() {
            r.push('?');
        }
        rest = t;
    }
    r.push_str(rest);
    r
}

fn run(name: &str, stress: bool) -> String {
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_luajit"));
    {
        use std::os::unix::process::CommandExt;
        cmd.arg0("luajit");
    }
    cmd.arg(format!("{name}.lua"))
        .current_dir(fixture_dir())
        .env_remove("LUA_INIT")
        .env_remove("LUA_PATH")
        .env_remove("LUA_CPATH");
    if stress {
        cmd.env("LUAJIT_RS_GCSTRESS", "1");
    } else {
        cmd.env_remove("LUAJIT_RS_GCSTRESS");
    }
    let out = cmd.stdin(Stdio::null()).output().unwrap();
    let mut s = String::from_utf8_lossy(&out.stdout).into_owned();
    if !out.stderr.is_empty() {
        s.push_str("--- stderr\n");
        s.push_str(&String::from_utf8_lossy(&out.stderr));
    }
    s.push_str(&format!("--- exit {}\n", out.status.code().unwrap_or(-1)));
    normalize(&s)
}

fn check(name: &str, stress: bool) {
    let expected = String::from_utf8_lossy(&std::fs::read(fixture_dir().join(format!("{name}.expected"))).unwrap()).into_owned();
    let got = run(name, stress);
    if got != expected {
        let first = got.lines().zip(expected.lines()).position(|(g, e)| g != e).unwrap_or(got.lines().count().min(expected.lines().count()));
        panic!(
            "{name} (stress {stress}) differs from the reference at line {}:\n  got:      {:?}\n  expected: {:?}\n--- full output ---\n{got}",
            first + 1,
            got.lines().nth(first),
            expected.lines().nth(first)
        );
    }
}

