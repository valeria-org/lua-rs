-- Exercises tests/capi/cmod.c through require and package.loadlib.
local cmod = require("cmod")
print(cmod == package.loaded.cmod, cmod.version, type(cmod.new))
local a = cmod.new()
print(pcall(a.mean, a))
a:add(1, 2, 3):add(4)
print(a:mean(), tostring(a))
print(pcall(a.add, a, "x"))
print(pcall(cmod.new().add, {}))
local t = cmod.map({1, 2, 3}, function(x) return x * x end)
print(#t, t[1], t[2], t[3])
print(pcall(cmod.map, {1}, function() error("in map") end))
local s = 0
for i in cmod.range(5) do s = s + i end
print("range sum", s)
local co = coroutine.wrap(function(...)
  local x = cmod.gen("first")
  print("gen resumed with", x)
  return cmod.gen()
end)
print(co())
print(co("again"))
print(pcall(cmod.gen, 1))
print(cmod.join(", ", "a", 1, 2.5, "z"))
print(cmod.env())
local sub = require("cmod.sub")
print(sub.name, package.loaded["cmod.sub"] == sub)
local f, err = package.loadlib(CMOD_PATH, "plain_function")
print(type(f), err)
print(f(1, 2, 3))
print(package.loadlib(CMOD_PATH, "no_such_symbol"))
print(select(3, package.loadlib("/nonexistent/lib.so", "x")))
local star = package.loadlib(CMOD_PATH, "*")
print(star)
print(pcall(require, "cmod.missing"))
